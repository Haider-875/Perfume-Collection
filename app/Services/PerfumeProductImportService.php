<?php

namespace App\Services;

use App\Models\Category;
use App\Models\Product;
use App\Models\ProductPrice;
use App\Models\ProductVariant;
use App\Models\ActivityLog;
use Illuminate\Http\UploadedFile;
use Illuminate\Support\Facades\DB;
use Illuminate\Support\Str;
use PhpOffice\PhpSpreadsheet\IOFactory;

class PerfumeProductImportService
{
    /**
     * Parse and validate an uploaded Excel or CSV file.
     *
     * @param UploadedFile $file
     * @param string $duplicateStrategy 'update', 'skip', or 'create'
     * @return array
     */
    public function parseAndValidate(UploadedFile $file, string $duplicateStrategy = 'update'): array
    {
        $filePath = $file->getRealPath();
        $spreadsheet = IOFactory::load($filePath);
        $sheet = $spreadsheet->getActiveSheet();
        $rawRows = $sheet->toArray(null, true, true, true);

        if (empty($rawRows) || count($rawRows) < 2) {
            return [
                'success' => false,
                'message' => 'The uploaded file is empty or does not contain data rows.',
                'rows' => [],
                'stats' => [
                    'total' => 0,
                    'valid' => 0,
                    'duplicates' => 0,
                    'errors' => 0,
                ],
            ];
        }

        // Extract and normalize header row (Row 1)
        $headerRow = array_shift($rawRows);
        $headerMap = $this->buildHeaderMap($headerRow);

        $parsedRows = [];
        $skuOccurrences = [];
        $totalFound = 0;
        $validCount = 0;
        $duplicateCount = 0;
        $errorCount = 0;

        // First pass: Count SKU occurrences within the file to catch duplicates
        foreach ($rawRows as $rowIdx => $cols) {
            if ($this->isRowBlank($cols)) {
                continue;
            }
            $skuRaw = trim((string)$this->getColValue($cols, $headerMap, 'sku'));
            if (!empty($skuRaw)) {
                $skuLower = strtolower($skuRaw);
                $skuOccurrences[$skuLower] = ($skuOccurrences[$skuLower] ?? 0) + 1;
            }
        }

        // Cache existing SKUs from DB
        $existingSkus = Product::pluck('id', 'sku')->toArray();
        $existingNames = Product::pluck('id', 'name')->mapWithKeys(function ($id, $name) {
            return [strtolower(trim($name)) => $id];
        })->toArray();

        $rowNumber = 1; // 1-based data index (Excel row will be rowNumber + 1)
        foreach ($rawRows as $excelRowIndex => $cols) {
            if ($this->isRowBlank($cols)) {
                continue;
            }

            $rowNumber++;
            $totalFound++;
            $errors = [];
            $warnings = [];

            // 1. Name (Required)
            $name = trim((string)$this->getColValue($cols, $headerMap, 'name'));
            if (empty($name)) {
                $errors[] = 'Perfume Name is required.';
            }

            // 2. Impression Of (Optional)
            $impressionOf = trim((string)$this->getColValue($cols, $headerMap, 'impression_of'));

            // 3. SKU (Auto-generate if empty)
            $sku = trim((string)$this->getColValue($cols, $headerMap, 'sku'));
            $isSkuAutoGenerated = false;

            if (empty($sku)) {
                $sku = $this->generateSku($name);
                $isSkuAutoGenerated = true;
                $warnings[] = "SKU was auto-generated as {$sku}.";
            } else {
                // Check within-file duplicates
                $skuLower = strtolower($sku);
                if (($skuOccurrences[$skuLower] ?? 0) > 1) {
                    $errors[] = "Duplicate SKU '{$sku}' occurs multiple times in this upload sheet.";
                }
            }

            // 4. Category
            $categoryName = trim((string)$this->getColValue($cols, $headerMap, 'category'));
            if (empty($categoryName)) {
                $categoryName = 'Signature Impressions';
            }

            // 5. Gender
            $genderRaw = trim((string)$this->getColValue($cols, $headerMap, 'gender'));
            $gender = $this->normalizeGender($genderRaw);

            // 6-9. Size Prices (PKR)
            $price30 = $this->parsePrice($this->getColValue($cols, $headerMap, 'price_30ml'));
            $price50 = $this->parsePrice($this->getColValue($cols, $headerMap, 'price_50ml'));
            $price60 = $this->parsePrice($this->getColValue($cols, $headerMap, 'price_60ml'));
            $price100 = $this->parsePrice($this->getColValue($cols, $headerMap, 'price_100ml'));

            $prices = [];
            if ($price30 !== null && $price30 > 0) $prices['30ml'] = $price30;
            if ($price50 !== null && $price50 > 0) $prices['50ml'] = $price50;
            if ($price60 !== null && $price60 > 0) $prices['60ml'] = $price60;
            if ($price100 !== null && $price100 > 0) $prices['100ml'] = $price100;

            if (empty($prices)) {
                $errors[] = 'At least one bottle size price (30ml, 50ml, 60ml, or 100ml) must be greater than 0.';
            }

            // 10. Stock
            $stockRaw = $this->getColValue($cols, $headerMap, 'stock');
            $stock = ($stockRaw !== null && is_numeric(trim((string)$stockRaw)))
                ? max(0, (int)trim((string)$stockRaw))
                : 25;

            // Check if product exists in database by SKU or exact Name
            $existingProductId = null;
            $existsInDb = false;

            if (isset($existingSkus[$sku])) {
                $existingProductId = $existingSkus[$sku];
                $existsInDb = true;
            } elseif (!empty($name) && isset($existingNames[strtolower($name)])) {
                $existingProductId = $existingNames[strtolower($name)];
                $existsInDb = true;
            }

            if ($existsInDb) {
                $duplicateCount++;
                if (empty($errors)) {
                    $warnings[] = "Existing perfume found in database (ID: #{$existingProductId}). Will {$duplicateStrategy}.";
                }
            }

            $isValid = empty($errors);
            if ($isValid) {
                $validCount++;
            } else {
                $errorCount++;
            }

            $parsedRows[] = [
                'excel_row' => $excelRowIndex,
                'name' => $name,
                'impression_of' => $impressionOf,
                'sku' => $sku,
                'is_sku_auto_generated' => $isSkuAutoGenerated,
                'category_name' => $categoryName,
                'gender' => $gender,
                'prices' => $prices,
                'stock' => $stock,
                'exists_in_db' => $existsInDb,
                'existing_product_id' => $existingProductId,
                'is_valid' => $isValid,
                'errors' => $errors,
                'warnings' => $warnings,
            ];
        }

        return [
            'success' => true,
            'filename' => $file->getClientOriginalName(),
            'rows' => $parsedRows,
            'stats' => [
                'total' => $totalFound,
                'valid' => $validCount,
                'duplicates' => $duplicateCount,
                'errors' => $errorCount,
            ],
            'duplicate_strategy' => $duplicateStrategy,
        ];
    }

    /**
     * Execute final database insertion for previewed rows.
     *
     * @param array $rows
     * @param string $duplicateStrategy
     * @return array
     */
    public function executeImport(array $rows, string $duplicateStrategy = 'update'): array
    {
        $createdCount = 0;
        $updatedCount = 0;
        $skippedCount = 0;
        $failedCount = 0;
        $failedRows = [];

        // Ensure product_prices table exists (important for Wasmer / serverless deployments)
        if (!\Illuminate\Support\Facades\Schema::hasTable('product_prices')) {
            try {
                \Illuminate\Support\Facades\Artisan::call('migrate', ['--force' => true]);
            } catch (\Throwable $e) {
                \Illuminate\Support\Facades\Log::warning('Auto-migration notice: ' . $e->getMessage());
            }
        }

        $defaultCategory = Category::firstOrCreate(
            ['name' => 'Signature Impressions'],
            ['slug' => 'signature-impressions']
        );

        $categoryCache = Category::pluck('id', 'name')->toArray();

        DB::beginTransaction();
        try {
            foreach ($rows as $item) {
                if (empty($item['is_valid'])) {
                    $failedCount++;
                    $failedRows[] = [
                        'row' => $item['excel_row'] ?? 0,
                        'name' => $item['name'] ?? '',
                        'sku' => $item['sku'] ?? '',
                        'reason' => implode(' | ', $item['errors'] ?? ['Validation failed']),
                    ];
                    continue;
                }

                $name = $item['name'];
                $impressionOf = $item['impression_of'];
                $sku = $item['sku'];
                $categoryName = $item['category_name'];
                $gender = $item['gender'];
                $prices = $item['prices'];
                $stock = $item['stock'];
                $existsInDb = $item['exists_in_db'];
                $existingProductId = $item['existing_product_id'];

                // Resolve category
                $categoryId = $categoryCache[$categoryName] ?? null;
                if (!$categoryId) {
                    $newCategory = Category::firstOrCreate(
                        ['name' => $categoryName],
                        ['slug' => Str::slug($categoryName)]
                    );
                    $categoryId = $newCategory->id;
                    $categoryCache[$categoryName] = $categoryId;
                }

                // Primary price calculation (lowest available size price)
                $primaryPrice = !empty($prices) ? min(array_values($prices)) : 0;

                // Handle existing product
                if ($existsInDb && $existingProductId) {
                    if ($duplicateStrategy === 'skip') {
                        $skippedCount++;
                        continue;
                    }

                    if ($duplicateStrategy === 'update') {
                        $product = Product::find($existingProductId);
                        if ($product) {
                            $product->name = $name;
                            $product->impression_of = $impressionOf;
                            $product->category_id = $categoryId;
                            $product->gender = $gender;
                            $product->stock = $stock;
                            $product->in_stock = $stock > 0;
                            $product->price = $primaryPrice;
                            $product->save();

                            $this->syncProductPricesAndVariants($product, $prices, $stock);
                            $updatedCount++;
                            continue;
                        }
                    }

                    if ($duplicateStrategy === 'create') {
                        // Collision on SKU: append random suffix for unique product creation
                        $sku .= '-CPY' . rand(10, 99);
                    }
                }

                // Create brand new product
                $slug = Str::slug($name);
                if (Product::where('slug', $slug)->exists()) {
                    $slug .= '-' . rand(100, 999);
                }

                $newProduct = Product::create([
                    'name' => $name,
                    'impression_of' => $impressionOf,
                    'slug' => $slug,
                    'sku' => $sku,
                    'category_id' => $categoryId,
                    'gender' => $gender,
                    'price' => $primaryPrice,
                    'stock' => $stock,
                    'in_stock' => $stock > 0,
                    'volume_ml' => isset($prices['100ml']) ? 100 : (isset($prices['50ml']) ? 50 : 30),
                    'concentration' => 'Extrait de Parfum (35% Oil)',
                    'longevity' => '14+ Hours Beast Mode',
                    'sillage' => 'Heavy / Room-Filling',
                    'thumbnail_image' => 'assets/images/perfumes/prod_oud_royale.jpg',
                    'is_active' => true,
                ]);

                $this->syncProductPricesAndVariants($newProduct, $prices, $stock);
                $createdCount++;
            }

            DB::commit();

            ActivityLog::record(
                'imported',
                "Bulk imported Excel/CSV perfume price list ({$createdCount} created, {$updatedCount} updated, {$skippedCount} skipped, {$failedCount} failed)"
            );

            return [
                'success' => true,
                'created_count' => $createdCount,
                'updated_count' => $updatedCount,
                'skipped_count' => $skippedCount,
                'failed_count' => $failedCount,
                'failed_rows' => $failedRows,
            ];
        } catch (\Throwable $e) {
            DB::rollBack();
            return [
                'success' => false,
                'message' => 'Import failed due to database error: ' . $e->getMessage(),
                'created_count' => 0,
                'updated_count' => 0,
                'skipped_count' => 0,
                'failed_count' => count($rows),
                'failed_rows' => [],
            ];
        }
    }

    /**
     * Synchronize ProductPrice records and ProductVariant records.
     */
    protected function syncProductPricesAndVariants(Product $product, array $prices, int $stock): void
    {
        $sizesMap = [
            '30ml' => 30,
            '50ml' => 50,
            '60ml' => 60,
            '100ml' => 100,
        ];

        foreach ($prices as $sizeLabel => $price) {
            // 1. Sync product_prices table
            ProductPrice::updateOrCreate(
                [
                    'product_id' => $product->id,
                    'size' => $sizeLabel,
                ],
                [
                    'price' => $price,
                ]
            );

            // 2. Sync product_variants table for multi-size storefront compatibility
            $ml = $sizesMap[$sizeLabel] ?? 50;
            $variantSku = $product->sku . '-' . $ml . 'ML';

            ProductVariant::updateOrCreate(
                [
                    'product_id' => $product->id,
                    'volume_ml' => $ml,
                ],
                [
                    'size_label' => $sizeLabel . ' Extrait de Parfum',
                    'price' => $price,
                    'sku' => $variantSku,
                    'stock' => $stock,
                    'is_default' => ($ml === 50 || $ml === 100),
                ]
            );
        }
    }

    /**
     * Map Excel column headers flexibly.
     */
    protected function buildHeaderMap(array $headerRow): array
    {
        $map = [];

        foreach ($headerRow as $colKey => $colHeader) {
            $h = strtolower(trim((string)$colHeader));
            $h = preg_replace('/[^a-z0-9]/', '', $h); // remove spaces, parentheses, underscores

            if (in_array($h, ['name', 'productname', 'perfumename', 'title'])) {
                $map['name'] = $colKey;
            } elseif (in_array($h, ['impressionof', 'impression', 'inspiredby', 'inspiredof', 'cloneof'])) {
                $map['impression_of'] = $colKey;
            } elseif (in_array($h, ['sku', 'code', 'productcode', 'itemcode'])) {
                $map['sku'] = $colKey;
            } elseif (in_array($h, ['category', 'categoryname', 'collection', 'family'])) {
                $map['category'] = $colKey;
            } elseif (in_array($h, ['gender', 'targetgender', 'type'])) {
                $map['gender'] = $colKey;
            } elseif (str_contains($h, '30ml') || str_contains($h, '30m') || $h === '30') {
                $map['price_30ml'] = $colKey;
            } elseif (str_contains($h, '50ml') || str_contains($h, '50m') || $h === '50') {
                $map['price_50ml'] = $colKey;
            } elseif (str_contains($h, '60ml') || str_contains($h, '60m') || $h === '60') {
                $map['price_60ml'] = $colKey;
            } elseif (str_contains($h, '100ml') || str_contains($h, '100m') || $h === '100') {
                $map['price_100ml'] = $colKey;
            } elseif (in_array($h, ['stock', 'quantity', 'qty', 'inventory', 'stockcount'])) {
                $map['stock'] = $colKey;
            }
        }

        return $map;
    }

    protected function getColValue(array $cols, array $headerMap, string $field)
    {
        if (isset($headerMap[$field]) && isset($cols[$headerMap[$field]])) {
            return $cols[$headerMap[$field]];
        }
        return null;
    }

    protected function isRowBlank(array $cols): bool
    {
        foreach ($cols as $val) {
            if ($val !== null && trim((string)$val) !== '') {
                return false;
            }
        }
        return true;
    }

    protected function parsePrice($val): ?float
    {
        if ($val === null) return null;
        $clean = preg_replace('/[^0-9.]/', '', (string)$val);
        if ($clean === '' || !is_numeric($clean)) return null;
        $price = (float)$clean;
        return $price > 0 ? $price : null;
    }

    protected function normalizeGender(string $gender): string
    {
        $g = strtolower(trim($gender));
        if (str_starts_with($g, 'm') && !str_contains($g, 'unisex')) return 'Men';
        if (str_starts_with($g, 'w') || str_starts_with($g, 'f')) return 'Women';
        return 'Unisex';
    }

    protected function generateSku(string $name): string
    {
        $words = preg_split('/\s+/', strtoupper(trim($name)));
        $prefix = '';
        foreach (array_slice($words, 0, 3) as $w) {
            $prefix .= substr($w, 0, 2);
        }
        if (strlen($prefix) < 3) {
            $prefix = strtoupper(substr($name, 0, 3));
        }
        $sku = 'RVH-' . substr($prefix, 0, 4) . '-' . rand(100, 999);
        while (Product::where('sku', $sku)->exists()) {
            $sku = 'RVH-' . substr($prefix, 0, 4) . '-' . rand(100, 999);
        }
        return $sku;
    }
}
